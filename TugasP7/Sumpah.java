
package TugasP7;

public class Sumpah {
    private String awal;

    public Sumpah() {
        awal = "Kami putra dan putri Indonesia";
    }

    public void pertama() { System.out.println(awal + " mengaku bertumpah darah yang satu, tanah Indonesia."); }
    public void kedua()   { System.out.println(awal + " mengaku berbangsa yang satu, bangsa Indonesia."); }
    public void ketiga()  { System.out.println(awal + " menjunjung bahasa persatuan, bahasa Indonesia."); }
}